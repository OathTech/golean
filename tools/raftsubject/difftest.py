#!/usr/bin/env python3
"""difftest.py — the DIFFERENTIAL OBLIGATION for plainpb's real logic.

The 2026-08-19 raftpb ruling (docs/2026-08-15_raft-push-p0-scoping.md §8.6)
requires that "any shim method with real logic (e.g. ConfState equivalence,
Entry/Message helpers raft's logic calls) gets a differential obligation —
probe it against upstream under go run and record the comparison".

plainpb has exactly three pieces of real logic that are NOT upstream text
kept verbatim:

  * `(*T).CloneMessage()`   generated, stands in for proto.Clone
  * `(*T).EqualMessage(y)`  generated, stands in for proto.Equal
  * `(*ConfState).Equivalent(cs2)`  overlay, upstream's algorithm with the
    two proto calls swapped for the two above

This script builds a throwaway Go module that links BOTH the upstream raftpb
(deps/raft, with the real protobuf runtime) and the derived plainpb, converts
values between them field by field, and runs a battery over every value shape
the type set admits — unset vs set-to-zero optional scalars, nil vs empty vs
non-empty repeated fields and bytes, nil vs non-nil nested messages, recursive
message lists. Every disagreement is printed; the exit code is the verdict.

    tools/raftsubject/difftest.py [--out DIR] [--keep]

The converters are GENERATED from the same struct field lists derive.py parses
out of raft.pb.go, so the probe cannot drift from the shim it probes.
"""

import argparse
import os
import shutil
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import derive  # noqa: E402

REPO = derive.REPO


def gen_conv(msgs, enums):
    out = ["// Code GENERATED by tools/raftsubject/difftest.py. DO NOT EDIT.",
           "//",
           "// Field-by-field converters between the upstream raftpb (with the",
           "// protobuf runtime) and the derived plainpb. Generated from the same",
           "// struct field lists derive.py parses, so the probe cannot drift from",
           "// the shim it probes.",
           "",
           "package main",
           "",
           "import (",
           '\tup "go.etcd.io/raft/v3/raftpb"',
           '\tpp "golean.local/plainpbdiff/plainpb"',
           ")",
           ""]
    for direction, (src, dst) in (("upToPlain", ("up", "pp")),
                                  ("plainToUp", ("pp", "up"))):
        for name, msg in msgs.items():
            out.append("func %s%s(x *%s.%s) *%s.%s {" % (direction, name, src, name, dst, name))
            out.append("\tif x == nil {")
            out.append("\t\treturn nil")
            out.append("\t}")
            out.append("\tout := &%s.%s{}" % (dst, name))
            for fname, ftype, _tag in msg.fields:
                base = ftype.lstrip("*[]")
                if ftype.startswith("*") and base in enums:
                    out += ["\tif x.%s != nil {" % fname,
                            "\t\tv := %s.%s(*x.%s)" % (dst, base, fname),
                            "\t\tout.%s = &v" % fname,
                            "\t}"]
                elif ftype.startswith("*") and base in ("uint64", "bool"):
                    out += ["\tif x.%s != nil {" % fname,
                            "\t\tv := *x.%s" % fname,
                            "\t\tout.%s = &v" % fname,
                            "\t}"]
                elif ftype.startswith("*") and base in msgs:
                    out += ["\tout.%s = %s%s(x.%s)" % (fname, direction, base, fname)]
                elif ftype == "[]byte":
                    out += ["\tif x.%s != nil {" % fname,
                            "\t\tout.%s = make([]byte, len(x.%s))" % (fname, fname),
                            "\t\tcopy(out.%s, x.%s)" % (fname, fname),
                            "\t}"]
                elif ftype.startswith("[]*") and base in msgs:
                    out += ["\tif x.%s != nil {" % fname,
                            "\t\tout.%s = make([]*%s.%s, len(x.%s))" % (fname, dst, base, fname),
                            "\t\tfor i := range x.%s {" % fname,
                            "\t\t\tout.%s[i] = %s%s(x.%s[i])" % (fname, direction, base, fname),
                            "\t\t}",
                            "\t}"]
                elif ftype.startswith("[]") and base == "uint64":
                    out += ["\tif x.%s != nil {" % fname,
                            "\t\tout.%s = make([]uint64, len(x.%s))" % (fname, fname),
                            "\t\tcopy(out.%s, x.%s)" % (fname, fname),
                            "\t}"]
                else:
                    derive.refuse("difftest: no converter rule for %s.%s %s"
                                  % (name, fname, ftype))
            out += ["\treturn out", "}", ""]
    return "\n".join(out)


MAIN_GO = r'''// The plainpb differential battery. See tools/raftsubject/difftest.py.
package main

import (
	"fmt"
	"os"

	up "go.etcd.io/raft/v3/raftpb"
	"google.golang.org/protobuf/proto"

	pp "golean.local/plainpbdiff/plainpb"
)

var fails int
var notes int

func report(kind, what string, wantUp, gotPlain any) {
	fails++
	fmt.Printf("DISAGREE %-10s %-46s upstream=%v plainpb=%v\n", kind, what, wantUp, gotPlain)
}

func u64(v uint64) *uint64 { return &v }
func bl(v bool) *bool      { return &v }

// ---- the ConfState battery -------------------------------------------------

type csDesc struct {
	name string
	cs   *up.ConfState
}

func confStates() []csDesc {
	return []csDesc{
		{"nil", nil},
		{"zero", &up.ConfState{}},
		{"empty-slices", &up.ConfState{Voters: []uint64{}, Learners: []uint64{}}},
		{"v123", &up.ConfState{Voters: []uint64{1, 2, 3}}},
		{"v321", &up.ConfState{Voters: []uint64{3, 2, 1}}},
		{"v1233", &up.ConfState{Voters: []uint64{1, 2, 3, 3}}},
		{"v12", &up.ConfState{Voters: []uint64{1, 2}}},
		{"v123-l4", &up.ConfState{Voters: []uint64{1, 2, 3}, Learners: []uint64{4}}},
		{"v123-l4-auto-unset", &up.ConfState{Voters: []uint64{1, 2, 3}, Learners: []uint64{4}}},
		{"v123-l4-auto-false", &up.ConfState{Voters: []uint64{1, 2, 3}, Learners: []uint64{4}, AutoLeave: bl(false)}},
		{"v123-l4-auto-true", &up.ConfState{Voters: []uint64{1, 2, 3}, Learners: []uint64{4}, AutoLeave: bl(true)}},
		{"joint", &up.ConfState{Voters: []uint64{1, 2, 3}, VotersOutgoing: []uint64{4, 5}, LearnersNext: []uint64{6}}},
		{"joint-perm", &up.ConfState{Voters: []uint64{3, 1, 2}, VotersOutgoing: []uint64{5, 4}, LearnersNext: []uint64{6}}},
	}
}

// ---- the general message battery -------------------------------------------

type msgDesc struct {
	name string
	up   any
	pp   any
	eq   func(a, b any) bool
	cl   func(a any) (any, any) // upstream clone, plain clone converted to upstream
}

func entries() []struct {
	name string
	e    *up.Entry
} {
	return []struct {
		name string
		e    *up.Entry
	}{
		{"nil", nil},
		{"zero", &up.Entry{}},
		{"term0-set", &up.Entry{Term: u64(0)}},
		{"term1", &up.Entry{Term: u64(1)}},
		{"term1-index2", &up.Entry{Term: u64(1), Index: u64(2)}},
		{"type-normal-set", &up.Entry{Type: up.EntryNormal.Enum()}},
		{"type-ccv2", &up.Entry{Type: up.EntryConfChangeV2.Enum()}},
		{"data-nil", &up.Entry{Data: nil}},
		{"data-empty", &up.Entry{Data: []byte{}}},
		{"data-ab", &up.Entry{Data: []byte("ab")}},
		{"data-ac", &up.Entry{Data: []byte("ac")}},
	}
}

func messages() []struct {
	name string
	m    *up.Message
} {
	e1 := &up.Entry{Term: u64(1), Index: u64(2), Data: []byte("x")}
	e2 := &up.Entry{Term: u64(1), Index: u64(3)}
	return []struct {
		name string
		m    *up.Message
	}{
		{"nil", nil},
		{"zero", &up.Message{}},
		{"type-app", &up.Message{Type: up.MsgApp.Enum()}},
		{"to-from", &up.Message{To: u64(2), From: u64(1)}},
		{"reject-false-set", &up.Message{Reject: bl(false)}},
		{"reject-true", &up.Message{Reject: bl(true)}},
		{"entries-nil", &up.Message{Entries: nil}},
		{"entries-empty", &up.Message{Entries: []*up.Entry{}}},
		{"entries-1", &up.Message{Entries: []*up.Entry{e1}}},
		{"entries-2", &up.Message{Entries: []*up.Entry{e1, e2}}},
		{"snapshot-nil", &up.Message{Snapshot: nil}},
		{"snapshot-zero", &up.Message{Snapshot: &up.Snapshot{}}},
		{"snapshot-meta", &up.Message{Snapshot: &up.Snapshot{Metadata: &up.SnapshotMetadata{Index: u64(7), ConfState: &up.ConfState{Voters: []uint64{1}}}}}},
		{"responses-1", &up.Message{Responses: []*up.Message{{To: u64(9)}}}},
		{"context-empty", &up.Message{Context: []byte{}}},
		{"context-c", &up.Message{Context: []byte("c")}},
	}
}

func confChangeV2s() []struct {
	name string
	c    *up.ConfChangeV2
} {
	return []struct {
		name string
		c    *up.ConfChangeV2
	}{
		{"nil", nil},
		{"zero", &up.ConfChangeV2{}},
		{"transition-auto-set", &up.ConfChangeV2{Transition: up.ConfChangeTransitionAuto.Enum()}},
		{"transition-explicit", &up.ConfChangeV2{Transition: up.ConfChangeTransitionJointExplicit.Enum()}},
		{"changes-1", &up.ConfChangeV2{Changes: []*up.ConfChangeSingle{{Type: up.ConfChangeAddNode.Enum(), NodeId: u64(3)}}}},
		{"changes-2", &up.ConfChangeV2{Changes: []*up.ConfChangeSingle{{NodeId: u64(3)}, {NodeId: u64(4)}}}},
		{"ctx", &up.ConfChangeV2{Context: []byte("q")}},
	}
}

func hardStates() []struct {
	name string
	h    *up.HardState
} {
	return []struct {
		name string
		h    *up.HardState
	}{
		{"nil", nil},
		{"zero", &up.HardState{}},
		{"term0-set", &up.HardState{Term: u64(0)}},
		{"t1v2c3", &up.HardState{Term: u64(1), Vote: u64(2), Commit: u64(3)}},
	}
}

func main() {
	// 1. ConfState.Equivalent: the ruling's named real-logic item.
	cs := confStates()
	pairs := 0
	for _, a := range cs {
		for _, b := range cs {
			pairs++
			wantErr := a.cs.Equivalent(b.cs)
			gotErr := upToPlainConfState(a.cs).Equivalent(upToPlainConfState(b.cs))
			if (wantErr == nil) != (gotErr == nil) {
				report("Equivalent", a.name+" ~ "+b.name, wantErr == nil, gotErr == nil)
			}
		}
	}
	fmt.Printf("ok  Equivalent          %d ordered pairs over %d ConfStates\n", pairs, len(cs))

	// 2. proto.Equal vs EqualMessage, per type.
	eqPairs := 0
	for _, a := range cs {
		for _, b := range cs {
			eqPairs++
			want := proto.Equal(a.cs, b.cs)
			got := upToPlainConfState(a.cs).EqualMessage(upToPlainConfState(b.cs))
			if want != got {
				report("Equal/CS", a.name+" = "+b.name, want, got)
			}
		}
	}
	for _, a := range entries() {
		for _, b := range entries() {
			eqPairs++
			want := proto.Equal(a.e, b.e)
			got := upToPlainEntry(a.e).EqualMessage(upToPlainEntry(b.e))
			if want != got {
				report("Equal/Entry", a.name+" = "+b.name, want, got)
			}
		}
	}
	for _, a := range messages() {
		for _, b := range messages() {
			eqPairs++
			want := proto.Equal(a.m, b.m)
			got := upToPlainMessage(a.m).EqualMessage(upToPlainMessage(b.m))
			if want != got {
				report("Equal/Msg", a.name+" = "+b.name, want, got)
			}
		}
	}
	for _, a := range confChangeV2s() {
		for _, b := range confChangeV2s() {
			eqPairs++
			want := proto.Equal(a.c, b.c)
			got := upToPlainConfChangeV2(a.c).EqualMessage(upToPlainConfChangeV2(b.c))
			if want != got {
				report("Equal/CCV2", a.name+" = "+b.name, want, got)
			}
		}
	}
	for _, a := range hardStates() {
		for _, b := range hardStates() {
			eqPairs++
			want := proto.Equal(a.h, b.h)
			got := upToPlainHardState(a.h).EqualMessage(upToPlainHardState(b.h))
			if want != got {
				report("Equal/HS", a.name+" = "+b.name, want, got)
			}
		}
	}
	fmt.Printf("ok  Equal               %d ordered pairs across 5 message types\n", eqPairs)

	// 3. proto.Clone vs CloneMessage. The verdict is taken with UPSTREAM's
	//    own equality over the two clones, so the shim's equality is not
	//    judging its own clone.
	clones := 0
	chk := func(kind, name string, wantAny, gotAny proto.Message) {
		clones++
		if !proto.Equal(wantAny, gotAny) {
			report("Clone/"+kind, name, wantAny, gotAny)
		}
	}
	for _, a := range cs {
		var wc *up.ConfState
		if a.cs != nil {
			wc = proto.Clone(a.cs).(*up.ConfState)
		}
		chk("CS", a.name, wc, plainToUpConfState(upToPlainConfState(a.cs).CloneMessage()))
	}
	for _, a := range entries() {
		var wc *up.Entry
		if a.e != nil {
			wc = proto.Clone(a.e).(*up.Entry)
		}
		chk("Entry", a.name, wc, plainToUpEntry(upToPlainEntry(a.e).CloneMessage()))
	}
	for _, a := range messages() {
		var wc *up.Message
		if a.m != nil {
			wc = proto.Clone(a.m).(*up.Message)
		}
		chk("Msg", a.name, wc, plainToUpMessage(upToPlainMessage(a.m).CloneMessage()))
	}
	for _, a := range confChangeV2s() {
		var wc *up.ConfChangeV2
		if a.c != nil {
			wc = proto.Clone(a.c).(*up.ConfChangeV2)
		}
		chk("CCV2", a.name, wc, plainToUpConfChangeV2(upToPlainConfChangeV2(a.c).CloneMessage()))
	}
	for _, a := range hardStates() {
		var wc *up.HardState
		if a.h != nil {
			wc = proto.Clone(a.h).(*up.HardState)
		}
		chk("HS", a.name, wc, plainToUpHardState(upToPlainHardState(a.h).CloneMessage()))
	}
	fmt.Printf("ok  Clone               %d values across 5 message types\n", clones)

	// 4. Clone must be a DEEP copy: mutating the clone must not touch the
	//    original (this is what raft relies on in log_unstable/storage/raft.go).
	orig := &pp.Snapshot{Data: []byte("d"), Metadata: &pp.SnapshotMetadata{
		Index: func() *uint64 { v := uint64(5); return &v }(),
		ConfState: &pp.ConfState{Voters: []uint64{1, 2}},
	}}
	cp := orig.CloneMessage()
	cp.Data[0] = 'e'
	*cp.Metadata.Index = 9
	cp.Metadata.ConfState.Voters[0] = 7
	if orig.Data[0] != 'd' || *orig.Metadata.Index != 5 || orig.Metadata.ConfState.Voters[0] != 1 {
		report("Clone/deep", "Snapshot aliasing", "original untouched", "original mutated")
	} else {
		fmt.Printf("ok  Clone deep-copy     nested bytes, *uint64 and []uint64 all unaliased\n")
	}

	// 5. Equivalent must not mutate its inputs (upstream operates on clones).
	in := &pp.ConfState{Voters: []uint64{3, 1, 2}}
	_ = in.Equivalent(&pp.ConfState{Voters: []uint64{1, 2, 3}})
	if in.Voters[0] != 3 || in.AutoLeave != nil {
		report("Equivalent", "input mutation", "inputs untouched", fmt.Sprint(in))
	} else {
		fmt.Printf("ok  Equivalent purity   inputs unsorted and AutoLeave still unset after the call\n")
	}

	// 6. The GO-LEVEL residual: proto.Equal cannot see nil-vs-empty on a
	//    repeated field (repeated fields have no presence), so section 3
	//    would pass even if the two clones differed there. Measured
	//    separately and REPORTED, not asserted — see the log's
	//    subject-delta ledger.
	nilness := func(kind, name string, wantNil, gotNil bool) {
		if wantNil != gotNil {
			fmt.Printf("NOTE     nilness   %-10s %-36s upstream-clone-nil=%v plainpb-clone-nil=%v\n",
				kind, name, wantNil, gotNil)
			notes++
		}
	}
	for _, a := range cs {
		if a.cs == nil {
			continue
		}
		wc := proto.Clone(a.cs).(*up.ConfState)
		gc := upToPlainConfState(a.cs).CloneMessage()
		nilness("CS.Voters", a.name, wc.Voters == nil, gc.Voters == nil)
		nilness("CS.Learners", a.name, wc.Learners == nil, gc.Learners == nil)
	}
	for _, a := range entries() {
		if a.e == nil {
			continue
		}
		wc := proto.Clone(a.e).(*up.Entry)
		gc := upToPlainEntry(a.e).CloneMessage()
		nilness("Entry.Data", a.name, wc.Data == nil, gc.Data == nil)
	}
	for _, a := range messages() {
		if a.m == nil {
			continue
		}
		wc := proto.Clone(a.m).(*up.Message)
		gc := upToPlainMessage(a.m).CloneMessage()
		nilness("Msg.Entries", a.name, wc.Entries == nil, gc.Entries == nil)
		nilness("Msg.Context", a.name, wc.Context == nil, gc.Context == nil)
	}
	fmt.Printf("ok  Clone nil-ness      %d Go-level nil/empty divergence(s) recorded (invisible to proto.Equal)\n", notes)

	if fails > 0 {
		fmt.Printf("\nFAIL %d disagreement(s)\n", fails)
		os.Exit(1)
	}
	fmt.Printf("\nPASS plainpb agrees with upstream raftpb on every probed value\n")
}
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=None)
    ap.add_argument("--keep", action="store_true")
    args = ap.parse_args()

    src = open(os.path.join(REPO, "deps", "raft", "raftpb", "raft.pb.go")).read()
    _text, msgs, enums, _stubs, _drops = derive.plainpb(src)

    out = args.out or tempfile.mkdtemp(prefix="plainpb-diff-")
    os.makedirs(out, exist_ok=True)
    shutil.rmtree(os.path.join(out, "plainpb"), ignore_errors=True)
    shutil.copytree(os.path.join(REPO, "raftsubject", "raftpb"),
                    os.path.join(out, "plainpb"))
    with open(os.path.join(out, "go.mod"), "w") as f:
        f.write("module golean.local/plainpbdiff\n\ngo 1.26\n\n"
                "require (\n\tgo.etcd.io/raft/v3 v3.0.0-00010101000000-000000000000\n"
                "\tgoogle.golang.org/protobuf v1.36.11\n)\n\n"
                "replace go.etcd.io/raft/v3 => %s\n"
                % os.path.join(REPO, "deps", "raft"))
    shutil.copy(os.path.join(REPO, "raftharness", "go.sum"),
                os.path.join(out, "go.sum"))
    with open(os.path.join(out, "conv.go"), "w") as f:
        f.write(gen_conv(msgs, enums))
    with open(os.path.join(out, "main.go"), "w") as f:
        f.write(MAIN_GO)

    env = dict(os.environ)
    env["GOCACHE"] = os.path.join(REPO, "artifacts", "go-build-cache")
    env["GOFLAGS"] = "-mod=mod"
    print("difftest: running go run in %s" % out)
    r = subprocess.run(["go", "run", "."], cwd=out, env=env)
    if not args.keep and args.out is None:
        shutil.rmtree(out)
    sys.exit(r.returncode)


if __name__ == "__main__":
    main()
