package main

// gclimits.go — gc's type-SIZE rejections and its «missing function
// body» rejection, refused after type-check (release-readiness row 34;
// [AGENT] lane frontend/chan-elem-limit-1013, 2026-10-13, under the
// [USER]'s 2026-10-12 backlog mandate, relayed; BUG-126 for the
// body-less half).
//
// go/types does not enforce gc's size limits; gc applies them in
// cmd/compile/internal/types/size.go (CalcSize) to the types it sizes,
// after type-checking, and rejects the whole compilation unit. Without
// this file the frontend lowered such programs and the machine answered
// them (`chan [9000]int`: `c == nil` → true) — a program gc rejects,
// answered (the BUG-125 class). The limits, measured against gc go1.26.5
// (the oracle pin) shape by shape (TestGcSizeLimits):
//
//   - TCHANARGS: `if t1.Elem().width >= 1<<16` → «channel element type
//     too large (>64kB)». The bound is >= 65536: `chan [8192]int`
//     (exactly 65536 bytes) is REJECTED, `chan [65535]byte` accepted.
//   - CalcArraySize: `n > (MaxWidth-1)/elem.width` → «type %L larger
//     than address space» (MaxWidth = 1<<50 on amd64, amd64/galign.go).
//   - calcStructOffset over a struct's fields, and over a function
//     type's receiver, parameters (end rounded to RegSize 8) and results
//     (TFUNCARGS): a field END `>= MaxWidth` → «type %L too large»,
//     which gc go1.26.5 reports as an internal compiler error («bad
//     type: …», typePos on an unnamed type): a rejection either way.
//
// WHAT IS SIZED — MENTIONS, NOT gc's SIZED SET; OVER-REFUSAL BY DESIGN
// ([USER] Mike 2026-10-13, relayed: «I feel like this is just opening
// the door to endless special-case nonsense. I'd prefer to just refuse
// this case, and maybe support it later»). Every type MENTIONED
// (reachable through array/slice/pointer/chan/map elements, struct
// fields, signatures, interface methods, named types' underlying) by
// any expression or declared object of every non-generic declaration of
// the program's source (non-library) units — dead or live, declared or
// used — plus the same inside every instantiated generic body. gc sizes
// less: its unified-IR writer drops function-local type and const
// declarations, blank `var _ T` without initializer, constant-false
// branches, `for false` bodies, constant-mismatched switch cases and
// statements after a terminating one, and constant expressions (an
// `unsafe.Sizeof` operand) are folded unsized. Those programs gc
// ACCEPTS and GoLean REFUSES, by name: the message appends
// gcMentionsClause. The pruning is NOT implemented; TestGcSizeLimits
// lists each such shape with both verdicts, the to-do list of a later
// «support it» lane. In the other direction the scan is exact on the
// generic boundary, which is not a pruning rule: uninstantiated generic
// code is never sized (gc accepts `func f[T any]() { var c chan
// [9000]T }` until something instantiates it at a type that makes the
// element too large, and an instantiation that appears only inside an
// uninstantiated body is not performed); genericity is read from
// go/types, never from the receiver's spelling.
//
// The refusal is a TYPE-CHECK-CLASS REJECTION of the whole program
// (`type-check: <pos>: <gc's message>[clause]`), never a per-declaration
// quarantine: gc rejects the compilation unit, so no part of the
// program may lower (the negative lane's frontend leg reads exactly
// this class). Every distinct offending type is named once, sorted by
// position; gc's own count and positions are artifacts of its type
// interning and of the compiler's current position when the deferred
// size check runs, so they are not reproduced — the verdict is.
//
// NOT mirrored here (recorded on release-readiness row 34): the stack
// frame limit (ssagen/pgen.go `>= 1<<30`, «stack frame too large
// (>1GB)»): it is a per-FUNCTION backend rule over the ABI-assigned
// argument area and the post-escape-analysis locals, also triggered by
// autogenerated wrappers (a named interface's method), not a type-size
// rule this walk can decide exactly.
//
// Generic bodies from packages loaded from export data (not source)
// cannot be instantiated here; in the pinned GOROOT no exported generic
// body builds a channel type from its type parameter (the one generic
// body that makes a channel of a local type, net's unexported
// doBlockingWithCtx, is instantiated only inside net).

import (
	"fmt"
	"go/ast"
	"go/token"
	"go/types"
	"sort"
	"strings"
)

const (
	gcMaxWidth     = int64(1) << 50 // amd64/galign.go arch.MAXWIDTH
	gcChanElemMax  = int64(1) << 16 // size.go TCHANARGS: width >= 1<<16 rejects
	gcSizeWorkCap  = 100000         // instantiation-closure bound (fail closed)
	gcChanElemText = "channel element type too large (>64kB)"
	// gcMentionsClause: appended to every size-limit refusal. The scan
	// sizes MENTIONS, not gc's sized set (see the file comment), so the
	// refusal may be wider than gc's rejection; the clause says so
	// ([USER] Mike 2026-10-13, relayed: «I'd prefer to just refuse this
	// case, and maybe support it later»).
	gcMentionsClause = " [GoLean sizes every mention of the type, including declarations and dead code that gc would not size; such a program is refused by name, not supported]"
	gcRegSize        = 8 // amd64 RegSize: TFUNCARGS rounds the params' end to it
)

type gcSizeViolation struct {
	pos token.Pos
	msg string
}

type gcDeclRef struct {
	decl *ast.FuncDecl
	unit *sourcePkg
}

type gcSizeScan struct {
	fset  *token.FileSet
	decls map[*types.Func]gcDeclRef
	ctxt  *types.Context
	// per-visit state
	unit *sourcePkg
	env  map[*types.TypeParam]types.Type
	pos  token.Pos
	// whole-scan state
	walked map[types.Type]bool
	queued map[string]bool
	queue  []gcSizeWork
	viol   map[string]gcSizeViolation
	err    error
}

type gcSizeWork struct {
	ref gcDeclRef
	env map[*types.TypeParam]types.Type
}

// checkGcSizeLimits refuses the program (a type-check-class rejection)
// if any type gc sizes breaks one of gc's size limits. units: every
// type-checked unit; seeds come from the non-library ones.
func checkGcSizeLimits(fset *token.FileSet, units []*sourcePkg) error {
	s := &gcSizeScan{
		fset:   fset,
		decls:  map[*types.Func]gcDeclRef{},
		ctxt:   types.NewContext(),
		walked: map[types.Type]bool{},
		queued: map[string]bool{},
		viol:   map[string]gcSizeViolation{},
	}
	for _, u := range units {
		for _, f := range u.files {
			for _, d := range f.Decls {
				if fd, ok := d.(*ast.FuncDecl); ok {
					if fn, ok := u.info.Defs[fd.Name].(*types.Func); ok {
						s.decls[fn] = gcDeclRef{decl: fd, unit: u}
					}
				}
			}
		}
	}
	// gc's «missing function body» (noder/writer.go funcDecl): a
	// body-less function or method in a -complete package (cmd/go
	// passes -complete when the package has no non-Go files; file
	// selection already refuses non-Go sources) is a rejection unless
	// it is //go:linkname'd in a file that imports "unsafe", or
	// //go:wasmimport'ed at GOARCH=wasm. NEITHER exemption is reachable
	// for a user unit since 2026-10-13 (BUG-127, directives.go): every
	// `//go:linkname` and `//go:wasmimport` refuses the export at file
	// selection, before this scan runs, so a body-less user declaration
	// is ALWAYS gc's rejection here. The linkname exemption this scan
	// carried (BUG-126, 2026-10-13) was removed with the directive
	// refusal rather than kept as dead code; library units (stdlib
	// source-through, where linknamed body-less functions are real) are
	// skipped, as before.
	for _, u := range units {
		if u.library {
			continue
		}
		for _, f := range u.files {
			for _, d := range f.Decls {
				if fd, ok := d.(*ast.FuncDecl); ok && fd.Body == nil {
					s.pos = fd.Name.Pos()
					s.record(fmt.Sprintf("bodyless:%p", fd), "missing function body")
				}
			}
		}
	}

	// Phase 1: every non-generic declaration of the source units.
	for _, u := range units {
		if u.library {
			continue
		}
		s.unit, s.env = u, nil
		for _, f := range u.files {
			for _, d := range f.Decls {
				switch d := d.(type) {
				case *ast.FuncDecl:
					if gcGenericFuncDecl(u.info, d) {
						continue
					}
					s.visit(d)
				case *ast.GenDecl:
					for _, sp := range d.Specs {
						if ts, ok := sp.(*ast.TypeSpec); ok && ts.TypeParams != nil {
							continue
						}
						s.visit(sp)
					}
				}
			}
		}
	}
	// Phase 2: the instantiation closure.
	for len(s.queue) > 0 && s.err == nil {
		w := s.queue[0]
		s.queue = s.queue[1:]
		s.unit, s.env = w.ref.unit, w.env
		d := w.ref.decl
		if d.Recv != nil {
			s.visit(d.Recv)
		}
		s.visit(d.Type.Params)
		if d.Type.Results != nil {
			s.visit(d.Type.Results)
		}
		if d.Body != nil {
			s.visit(d.Body)
		}
	}
	if s.err != nil {
		return s.err
	}
	if len(s.viol) == 0 {
		return nil
	}
	vs := make([]gcSizeViolation, 0, len(s.viol))
	for _, v := range s.viol {
		vs = append(vs, v)
	}
	sort.Slice(vs, func(i, j int) bool {
		pi, pj := fset.Position(vs[i].pos), fset.Position(vs[j].pos)
		if pi.Filename != pj.Filename {
			return pi.Filename < pj.Filename
		}
		if pi.Line != pj.Line {
			return pi.Line < pj.Line
		}
		if pi.Column != pj.Column {
			return pi.Column < pj.Column
		}
		return vs[i].msg < vs[j].msg
	})
	lines := make([]string, len(vs))
	for i, v := range vs {
		lines[i] = fmt.Sprintf("%s: %s", fset.Position(v.pos), v.msg)
	}
	return fmt.Errorf("type-check: %s", strings.Join(lines, "\ntype-check: "))
}

// gcGenericFuncDecl: a function with type parameters, or a method of a
// generic type — read from go/types (the declared object's signature),
// never from the receiver's spelling (`(*G[T])`, `((*G[T]))` are the
// same receiver; review HIGH-2).
func gcGenericFuncDecl(info *types.Info, d *ast.FuncDecl) bool {
	fn, ok := info.Defs[d.Name].(*types.Func)
	if !ok {
		return false // no object (cannot happen after type-check): sized, the fail-closed side
	}
	sig := fn.Type().(*types.Signature)
	return sig.TypeParams().Len() > 0 || sig.RecvTypeParams().Len() > 0
}

// visit sizes every type recorded for the nodes under n (expressions,
// defined and implicit objects, instantiations) at the current env.
// Uses are not read: every use that denotes a value is itself an
// expression in info.Types; a use of a generic object denotes its
// uninstantiated ORIGIN, whose instances arrive through Instances.
func (s *gcSizeScan) visit(n ast.Node) {
	info := s.unit.info
	ast.Inspect(n, func(n ast.Node) bool {
		if n == nil || s.err != nil {
			return false
		}
		switch x := n.(type) {
		case *ast.FuncDecl:
			// Only the top-level decl itself is visited (callers pass
			// its parts); nested FuncDecls do not exist.
		case *ast.Ident:
			if obj := info.Defs[x]; obj != nil {
				s.sizeObj(x.Pos(), obj)
			}
			if inst, ok := info.Instances[x]; ok {
				s.instance(x, inst)
			}
		}
		if obj := info.Implicits[n]; obj != nil {
			s.sizeObj(n.Pos(), obj)
		}
		if e, ok := n.(ast.Expr); ok {
			if tv, ok := info.Types[e]; ok && tv.Type != nil {
				s.size(e.Pos(), tv.Type)
			}
		}
		return true
	})
}

func (s *gcSizeScan) sizeObj(pos token.Pos, obj types.Object) {
	switch o := obj.(type) {
	case *types.PkgName, *types.Label, *types.Nil, *types.Builtin:
		return
	case *types.TypeName:
		if _, ok := o.Type().(*types.TypeParam); ok {
			return
		}
	}
	if obj.Type() != nil {
		s.size(pos, obj.Type())
	}
}

// instance handles one Instances entry: the instantiated type is sized;
// a generic FUNCTION instantiated at concrete arguments queues its body.
func (s *gcSizeScan) instance(id *ast.Ident, inst types.Instance) {
	targs := make([]types.Type, inst.TypeArgs.Len())
	for i := range targs {
		t, ok := s.concrete(inst.TypeArgs.At(i))
		if !ok {
			return // mentions a type parameter not bound here: not an instantiation gc performs at this point
		}
		targs[i] = t
		s.walkAt(id.Pos(), t)
	}
	s.size(id.Pos(), inst.Type)
	fn, ok := s.unit.info.Uses[id].(*types.Func)
	if !ok {
		return
	}
	sig, ok := fn.Origin().Type().(*types.Signature)
	if !ok || sig.TypeParams().Len() != len(targs) {
		return
	}
	s.enqueue(fn.Origin(), sig.TypeParams(), targs)
}

func (s *gcSizeScan) enqueue(fn *types.Func, tps *types.TypeParamList, targs []types.Type) {
	ref, ok := s.decls[fn]
	if !ok || ref.decl.Body == nil {
		return // body not in source (export data): see the file comment
	}
	keyParts := make([]string, len(targs))
	env := map[*types.TypeParam]types.Type{}
	for i, t := range targs {
		keyParts[i] = types.TypeString(t, nil)
		env[tps.At(i)] = t
	}
	key := fmt.Sprintf("%p[%s]", ref.decl, strings.Join(keyParts, ";"))
	if s.queued[key] {
		return
	}
	if len(s.queued) >= gcSizeWorkCap {
		s.err = unsup("gc size-limit check: more than %d generic instantiations — refusing rather than leaving the rest unsized", gcSizeWorkCap)
		return
	}
	s.queued[key] = true
	s.queue = append(s.queue, gcSizeWork{ref: ref, env: env})
}

// size substitutes the current env into t; a type that still mentions a
// type parameter not bound by the env belongs to an uninstantiated
// generic ORIGIN (not sized by gc) and is skipped.
func (s *gcSizeScan) size(pos token.Pos, t types.Type) {
	ct, ok := s.concrete(t)
	if !ok {
		return
	}
	s.walkAt(pos, ct)
}

func (s *gcSizeScan) walkAt(pos token.Pos, t types.Type) {
	s.pos = pos
	s.walk(t)
}

func (s *gcSizeScan) concrete(t types.Type) (types.Type, bool) {
	if gcMentionsUnbound(t, s.env, map[types.Type]bool{}) {
		return nil, false
	}
	if s.env == nil {
		return t, true
	}
	ct, err := s.subst(t, map[*types.Named]*types.Named{})
	if err != nil {
		if s.err == nil {
			s.err = unsup("gc size-limit check: %v", err)
		}
		return nil, false
	}
	return ct, true
}

// gcMentionsUnbound: t mentions a type parameter the env does not bind.
// Function-local named types are entered (a type declared inside a
// generic body may mention the body's parameters through its underlying
// type); package-level named types only through their type arguments.
func gcMentionsUnbound(t types.Type, env map[*types.TypeParam]types.Type, seen map[types.Type]bool) bool {
	if seen[t] {
		return false
	}
	seen[t] = true
	rec := func(u types.Type) bool { return gcMentionsUnbound(u, env, seen) }
	switch ty := t.(type) {
	case *types.TypeParam:
		_, ok := env[ty]
		return !ok
	case *types.Basic:
		return false
	case *types.Named:
		if ty.TypeParams().Len() > 0 && ty.TypeArgs().Len() == 0 {
			return true // an uninstantiated generic type
		}
		for i := 0; i < ty.TypeArgs().Len(); i++ {
			if rec(ty.TypeArgs().At(i)) {
				return true
			}
		}
		if gcLocalNamed(ty) {
			return rec(ty.Underlying())
		}
		return false
	case *types.Alias:
		return rec(types.Unalias(ty))
	case *types.Pointer:
		return rec(ty.Elem())
	case *types.Slice:
		return rec(ty.Elem())
	case *types.Array:
		return rec(ty.Elem())
	case *types.Chan:
		return rec(ty.Elem())
	case *types.Map:
		return rec(ty.Key()) || rec(ty.Elem())
	case *types.Signature:
		if ty.TypeParams().Len() > 0 {
			return true // a generic function's uninstantiated signature
		}
		return rec(ty.Params()) || rec(ty.Results())
	case *types.Tuple:
		for i := 0; i < ty.Len(); i++ {
			if rec(ty.At(i).Type()) {
				return true
			}
		}
		return false
	case *types.Struct:
		for i := 0; i < ty.NumFields(); i++ {
			if rec(ty.Field(i).Type()) {
				return true
			}
		}
		return false
	case *types.Interface:
		for i := 0; i < ty.NumEmbeddeds(); i++ {
			if rec(ty.EmbeddedType(i)) {
				return true
			}
		}
		for i := 0; i < ty.NumExplicitMethods(); i++ {
			if rec(ty.ExplicitMethod(i).Type()) {
				return true
			}
		}
		return false
	default:
		return true // unknown shape (a constraint union): never sized
	}
}

// gcLocalNamed: a named type declared inside a function body.
func gcLocalNamed(n *types.Named) bool {
	obj := n.Obj()
	return obj.Pkg() != nil && obj.Parent() != nil && obj.Parent() != obj.Pkg().Scope() && obj.Parent() != types.Universe
}

// subst applies the env. Instantiated named types go through
// types.Instantiate (go/types' own subster, as mono.go does); a
// function-local named type is rebuilt over its substituted underlying
// (a fresh Named, memoized for recursive local types).
func (s *gcSizeScan) subst(t types.Type, memo map[*types.Named]*types.Named) (types.Type, error) {
	rec := func(u types.Type) (types.Type, error) { return s.subst(u, memo) }
	switch ty := t.(type) {
	case *types.TypeParam:
		sub, ok := s.env[ty]
		if !ok {
			return nil, fmt.Errorf("unbound type parameter %s", ty)
		}
		return sub, nil
	case *types.Basic:
		return ty, nil
	case *types.Named:
		if args := ty.TypeArgs(); args.Len() > 0 {
			newArgs := make([]types.Type, args.Len())
			for i := range newArgs {
				a, err := rec(args.At(i))
				if err != nil {
					return nil, err
				}
				newArgs[i] = a
			}
			inst, err := types.Instantiate(s.ctxt, ty.Origin(), newArgs, false)
			if err != nil {
				return nil, fmt.Errorf("instantiate %s: %v", ty.Origin(), err)
			}
			return inst, nil
		}
		if !gcLocalNamed(ty) {
			return ty, nil
		}
		if n, ok := memo[ty]; ok {
			return n, nil
		}
		n := types.NewNamed(types.NewTypeName(ty.Obj().Pos(), ty.Obj().Pkg(), ty.Obj().Name(), nil), nil, nil)
		memo[ty] = n
		u, err := rec(ty.Underlying())
		if err != nil {
			return nil, err
		}
		n.SetUnderlying(u.Underlying())
		return n, nil
	case *types.Alias:
		return rec(types.Unalias(ty))
	case *types.Pointer:
		e, err := rec(ty.Elem())
		if err != nil {
			return nil, err
		}
		return types.NewPointer(e), nil
	case *types.Slice:
		e, err := rec(ty.Elem())
		if err != nil {
			return nil, err
		}
		return types.NewSlice(e), nil
	case *types.Array:
		e, err := rec(ty.Elem())
		if err != nil {
			return nil, err
		}
		return types.NewArray(e, ty.Len()), nil
	case *types.Chan:
		e, err := rec(ty.Elem())
		if err != nil {
			return nil, err
		}
		return types.NewChan(ty.Dir(), e), nil
	case *types.Map:
		k, err := rec(ty.Key())
		if err != nil {
			return nil, err
		}
		v, err := rec(ty.Elem())
		if err != nil {
			return nil, err
		}
		return types.NewMap(k, v), nil
	case *types.Signature:
		p, err := rec(ty.Params())
		if err != nil {
			return nil, err
		}
		r, err := rec(ty.Results())
		if err != nil {
			return nil, err
		}
		return types.NewSignatureType(nil, nil, nil, p.(*types.Tuple), r.(*types.Tuple), ty.Variadic()), nil
	case *types.Tuple:
		if ty == nil {
			return (*types.Tuple)(nil), nil
		}
		vars := make([]*types.Var, ty.Len())
		for i := range vars {
			v := ty.At(i)
			vt, err := rec(v.Type())
			if err != nil {
				return nil, err
			}
			vars[i] = types.NewVar(v.Pos(), v.Pkg(), v.Name(), vt)
		}
		return types.NewTuple(vars...), nil
	case *types.Struct:
		fields := make([]*types.Var, ty.NumFields())
		tags := make([]string, ty.NumFields())
		for i := range fields {
			f := ty.Field(i)
			ft, err := rec(f.Type())
			if err != nil {
				return nil, err
			}
			fields[i] = types.NewField(f.Pos(), f.Pkg(), f.Name(), ft, f.Anonymous())
			tags[i] = ty.Tag(i)
		}
		return types.NewStruct(fields, tags), nil
	case *types.Interface:
		fns := make([]*types.Func, ty.NumExplicitMethods())
		for i := range fns {
			m := ty.ExplicitMethod(i)
			mt, err := rec(m.Type())
			if err != nil {
				return nil, err
			}
			fns[i] = types.NewFunc(m.Pos(), m.Pkg(), m.Name(), mt.(*types.Signature))
		}
		embeds := make([]types.Type, ty.NumEmbeddeds())
		for i := range embeds {
			et, err := rec(ty.EmbeddedType(i))
			if err != nil {
				return nil, err
			}
			embeds[i] = et
		}
		ni := types.NewInterfaceType(fns, embeds)
		ni.Complete()
		return ni, nil
	default:
		return nil, fmt.Errorf("substitution into %T (%s)", t, t)
	}
}

// walk sizes a CONCRETE type and everything gc sizes with it, recording
// violations; a concrete instance of a generic named type queues its
// methods' bodies (gc instantiates the methods of every instantiated
// type it compiles — measured: a generic type's method body is sized
// at `type X struct{ g G[int] }`, not when G is never instantiated).
func (s *gcSizeScan) walk(t types.Type) {
	if s.walked[t] || s.err != nil {
		return
	}
	s.walked[t] = true
	switch ty := t.(type) {
	case *types.Basic, *types.TypeParam:
		// TypeParam cannot reach here (concrete() filtered it).
	case *types.Named:
		if ty.TypeParams().Len() > 0 && ty.TypeArgs().Len() == 0 {
			return // uninstantiated generic type (filtered by concrete())
		}
		if args := ty.TypeArgs(); args.Len() > 0 {
			origin := ty.Origin()
			targs := make([]types.Type, args.Len())
			for i := range targs {
				targs[i] = args.At(i)
			}
			for i := 0; i < origin.NumMethods(); i++ {
				m := origin.Method(i)
				sig, ok := m.Type().(*types.Signature)
				if !ok || sig.RecvTypeParams().Len() != len(targs) {
					continue
				}
				s.enqueue(m, sig.RecvTypeParams(), targs)
			}
		}
		s.walk(ty.Underlying())
	case *types.Alias:
		s.walk(types.Unalias(ty))
	case *types.Pointer:
		s.walk(ty.Elem())
	case *types.Slice:
		s.walk(ty.Elem())
	case *types.Array:
		if w := gcSizes.Sizeof(ty.Elem()); w < 0 || (w > 0 && ty.Len() > (gcMaxWidth-1)/w) {
			msg := fmt.Sprintf("type %s larger than address space", types.TypeString(ty, nil))
			s.record(msg, msg+gcMentionsClause)
		}
		s.walk(ty.Elem())
	case *types.Chan:
		if w := gcSizes.Sizeof(ty.Elem()); w < 0 || w >= gcChanElemMax {
			s.record("chan:"+types.TypeString(ty, nil), gcChanElemText+gcMentionsClause)
		}
		s.walk(ty.Elem())
	case *types.Map:
		s.walk(ty.Key())
		s.walk(ty.Elem())
	case *types.Struct:
		if n := ty.NumFields(); n > 0 {
			vars := make([]*types.Var, n)
			for i := range vars {
				vars[i] = ty.Field(i)
			}
			offs := gcSizes.Offsetsof(vars)
			for i, v := range vars {
				sz := gcSizes.Sizeof(v.Type())
				if offs[i] < 0 || sz < 0 || offs[i] >= gcMaxWidth || sz >= gcMaxWidth || offs[i]+sz >= gcMaxWidth {
					msg := fmt.Sprintf("type %s too large", types.TypeString(ty, nil))
					s.record(msg, msg+gcMentionsClause)
					break
				}
			}
		}
		for i := 0; i < ty.NumFields(); i++ {
			s.walk(ty.Field(i).Type())
		}
	case *types.Signature:
		if gcFuncArgsTooLarge(ty) {
			msg := fmt.Sprintf("type %s too large", types.TypeString(ty, nil))
			s.record(msg, msg+gcMentionsClause)
		}
		s.walk(ty.Params())
		s.walk(ty.Results())
	case *types.Tuple:
		if ty == nil {
			return
		}
		for i := 0; i < ty.Len(); i++ {
			s.walk(ty.At(i).Type())
		}
	case *types.Interface:
		for i := 0; i < ty.NumMethods(); i++ {
			s.walk(ty.Method(i).Type())
		}
	default:
		s.err = unsup("gc size-limit check: unexpected type %T (%s)", t, t)
	}
}

// gcFuncArgsTooLarge mirrors CalcSize's TFUNCARGS arm: calcStructOffset
// over the receiver, then the parameters (continuing the offset), the
// offset rounded up to RegSize, then the results; each field is placed
// at its alignment and any field END >= MaxWidth is gc's «type … too
// large» (go1.26.5 then ICEs, «bad type: func(…)», like the struct arm).
func gcFuncArgsTooLarge(sig *types.Signature) bool {
	off := int64(0)
	over := false
	place := func(v *types.Var) {
		if over {
			return
		}
		sz, al := gcSizes.Sizeof(v.Type()), gcSizes.Alignof(v.Type())
		if sz < 0 || sz >= gcMaxWidth || al <= 0 {
			over = true
			return
		}
		off = (off + al - 1) / al * al
		off += sz
		if off >= gcMaxWidth {
			over = true
		}
	}
	if r := sig.Recv(); r != nil {
		place(r)
	}
	for i := 0; i < sig.Params().Len(); i++ {
		place(sig.Params().At(i))
	}
	off = (off + gcRegSize - 1) / gcRegSize * gcRegSize
	for i := 0; i < sig.Results().Len(); i++ {
		place(sig.Results().At(i))
	}
	return over
}

// record keeps one violation per offending type (key), at the earliest
// position the walk records for it — not necessarily the type's first
// mention in the source: the walk dedups by type identity, so a mention
// reached earlier through an already-walked identical type is not seen.
func (s *gcSizeScan) record(key, msg string) {
	if v, ok := s.viol[key]; ok && v.pos <= s.pos {
		return
	}
	s.viol[key] = gcSizeViolation{pos: s.pos, msg: msg}
}
