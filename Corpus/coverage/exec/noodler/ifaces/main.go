// Embedded interface in a struct, nil: calling through it panics.
type HasValuer struct {
	Valuer
	extra int
}

func embeddedInterfaceNilCall() int {
	h := HasValuer{extra: 1}
	return h.Val()
}

// Embedded interface present: promoted call dispatches dynamically.
func embeddedInterfaceCall() int {
	h := HasValuer{Valuer: Inner{9}, extra: 1}
	var v Valuer = h
	return v.Val() + h.extra
}

