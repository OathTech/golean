// `case 1` against an interface holding int64(1): the constant converts
// to `any` as int, so int64(1) does not match.
func switchInterfaceTypedConstant() (int, int) {
	var x any = int64(1)
	var y any = 1
	r1, r2 := 0, 0
	switch x {
	case 1:
		r1 = 1
	default:
		r1 = 2
	}
	switch y {
	case 1:
		r2 = 1
	default:
		r2 = 2
	}
	return r1, r2
}

// `case nil` in an expression switch on an interface, and a typed nil
// pointer that is NOT nil as an interface.
func switchInterfaceNil() (int, int) {
	var a any
	var p *int
	var b any = p
	r1, r2 := 0, 0
	switch a {
	case nil:
		r1 = 1
	default:
		r1 = 2
	}
	switch b {
	case nil:
		r2 = 1
	default:
		r2 = 2
	}
	return r1, r2
}

// A NaN boxed in an interface is not equal to itself, and two NaN boxes
// are not equal; the comparison does not panic.
func nanInInterface() (bool, bool, bool) {
	zero := 0.0
	nan := zero / zero
	var a any = nan
	var b any = nan
	return a == a, a == b, a != b
}

