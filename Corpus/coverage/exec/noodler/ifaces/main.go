type Inner struct{ v int }

func (i Inner) Val() int   { return i.v }
func (i *Inner) PVal() int { return i.v + 100 }

// Method with a pointer receiver that never touches the receiver.
func (i *Inner) Const() int { return 7 }

type Outer struct{ *Inner }

// Calling a promoted value-receiver method through a nil embedded
// pointer dereferences it: panic.
func promotedValueMethodThroughNil() int {
	var o Outer
	return o.Val()
}

// Calling a promoted pointer-receiver method that ignores the receiver
// through a nil embedded pointer does NOT panic.
func promotedPointerMethodThroughNilOK() int {
	var o Outer
	return o.Const()
}

// ...but one that reads a field does.
func promotedPointerMethodThroughNilRead() int {
	var o Outer
	return o.PVal()
}

// Interface satisfied via promotion through an embedded pointer;
// the dynamic value is the Outer struct.
type Valuer interface{ Val() int }

func promotedSatisfiesInterface() int {
	o := Outer{&Inner{5}}
	var v Valuer = o
	return v.Val()
}

// Method value taken from an interface holding a nil *Inner with a
