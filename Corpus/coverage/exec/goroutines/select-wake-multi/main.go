package main

// L2 WAKE-PATH envelope pin (slice 4): a parked select whose channels
// become ready via CELL changes (two closes — closes never pair, so the
// select wakes on cell readiness). The clause order lists b FIRST so the
// wake rule's determinism is visible: waking between the closes commits
// the a-clause (the only ready one); waking after both commits the
// FIRST wake-ready clause in clause order (b) — NO re-randomization on
// the blocked path (design D4; gc probe-pinned: a woken select commits
// the case its waking event belongs to, never a fresh shuffle). The
// admitted set {1, 2} is generated by L1 wake-timing latitude plus the
// entry-path L2 pick (a schedule where both closes land before the
// select entry); gc realizes 1 on park-first schedules (woken by
// close(a)) and either member on entry-multi-ready schedules.

func selectWakeMulti() int {
	a := make(chan int, 1)
	b := make(chan int, 1)
	done := make(chan int)
	go func() {
		close(a)
		close(b)
		done <- 1
	}()
	got := 0
	select {
	case <-b:
		got = 2
	case <-a:
		got = 1
	}
	<-done
	return got
}

func main() {
	println(selectWakeMulti())
}
