// SCHEDULE-DEPENDENT observables — deliberately RED-PINNED for slice 4
// (charter: the membership lane's enumerator over schedules). The
// observation genuinely varies with the schedule (which sender commits
// first is pure L1 latitude), so the strict lane's three-stream
// invariance check must refuse it; the membership lane will own it.

func schedFirstCome() int {
	ch := make(chan int, 2)
	done := make(chan int)
	go func() {
		ch <- 1
		done <- 0
	}()
	go func() {
		ch <- 2
		done <- 0
	}()
	<-done
	<-done
	first := <-ch
	second := <-ch
	return first*10 + second // 12 or 21, by schedule
}


// Select-with-default against a maybe-parked partner (S2 audit, major
// finding: waiter-blind select readiness): whether the worker has
// PARKED at its send before main's select decides is pure L1 latitude,
// so the observation set is {7, 99} — go1.26.5 measured 199970/30 over
// 200000 runs (audit verifier probe). The waiter-aware readiness fix
// makes 7 reachable in the model; schedule enumeration (slice 4) owns
// certifying the set.
func schedSelectDefaultHandshake() int {
	ready := make(chan int)
	ch := make(chan int)
	go func() {
		ready <- 1
		ch <- 7
	}()
	<-ready
	select {
	case v := <-ch:
		return v
	default:
		return 99
	}
}

// Buffer-occupancy observation with a maybe-parked receiver (S2 audit,
// major finding: buffered sends bypassed parked waiters): if the
// worker is parked at its receive when main's send arrives, gc hands
// off DIRECTLY (len stays 0); if the worker has not arrived, the send
// buffers (len 1 until the worker drains). The observation set is
// {100, 110}; only the waiter-priority model reaches gc's dominant
// handoff outcome. Schedule enumeration (slice 4) owns the set.
func schedLenHandoff() int {
	ready := make(chan int)
	ch := make(chan int, 2)
	done := make(chan int)
	go func() {
		ready <- 1
		v := <-ch
		done <- v
	}()
	<-ready
	ch <- 1
	l := len(ch)
	r := <-done
	return r*100 + l*10
}

// THE L4 WAITER-PICK site at width > 1 (slice 6, envelope-width
// review; scope corrected at the arc-final audit F3, 2026-08-08):
// with BOTH senders parked on the ONE unbuffered channel when
// main's receive arrives, the arrival pairing must choose among TWO
// matching parked waiters — the corpus shape whose certified tree
// consumes the L4 pick above width 1 OBSERVABLY. (The slice-6 claim
// that this was the ONLY such tree was wrong: schedFirstCome's `done`
// channel — unbuffered, both goroutines send, main receives twice —
// already consumed 336 width-2 L4 sites in its certified tree, but
// observationally inertly, both senders sending 0.
// select-arrival-multi's parked senders do sit on different channels,
// so the choice there is the L2 clause pick.) The receive order
// {12, 21} is generated by L1 arrival timing
// AND, on both-parked branches, the L4 waiter pick; go1.26.5 exhibits
// both members (plain samples sit on one; the -race half exhibits
// both — the dual-sampling doctrine's perturbation at work).
func schedWaiterPick() int {
	ch := make(chan int)
	go func() { ch <- 1 }()
	go func() { ch <- 2 }()
	a := <-ch
	b := <-ch
	return a*10 + b // 12 or 21, by schedule + waiter pick
}

// A pure, registry-free delay: a finite recursion the machine steps
// through without any scheduling point (no loop back-edge, no registry
// op). It makes gc exhibit the peer's send between the two reads below
// at a useful rate; the machine's set does not depend on it.
//
//go:noinline
func schedDelay(n int) int {
	if n == 0 {
		return 0
	}
	return n + schedDelay(n-1)
}

// TWO channel-length reads around a pure delay, with a peer's buffered
// send in flight (the Codex release-trust review's F1 witness,
// 2026-10-12, relayed by the [USER]; BUG-123). `len(ch)` reads the
// buffer count — shared state the peer's send changes with no
// synchronization required (spec#Channel_types, spec#Length_and_
// capacity) and no footprint the race detector sees (gc's `chanlen` is
// uninstrumented; inventory U2) — so the send may land before the
// first read (11), between the two (1) or after both (0). On `main`
// before this lane the read opened no scheduling boundary and the
// machine certified exactly {0, 11}; gc go1.26.5 (GOMAXPROCS=2, -race,
// 10,000 calls) realized 0/1/11 at 9861/72/67. The channel-length
// apply is a registry boundary since this lane: certified set
// {0, 1, 11}.
func schedLenPeerSend() int {
	ch := make(chan int, 1)
	go func() { ch <- 1 }()
	a := len(ch)
	_ = schedDelay(100)
	b := len(ch)
	<-ch
	return 10*a + b // 0, 1 or 11, by schedule
}

func main() {
	schedFirstCome()
	schedSelectDefaultHandshake()
	schedLenHandoff()
	schedWaiterPick()
	schedLenPeerSend()
}
