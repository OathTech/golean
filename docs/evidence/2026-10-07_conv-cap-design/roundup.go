const (
	maxSmallSize     = 32768
	smallSizeDiv     = 8
	smallSizeMax     = 1024
	largeSizeDiv     = 128
	mallocHeaderSize = 8
	pageSize         = 8192
)

func divRoundUp(n, a uintptr) uintptr { return (n + a - 1) / a }

// roundupsize for noscan allocations (no malloc header is ever added).
func roundupsize(size uintptr) uintptr {
	reqSize := size
	if reqSize <= maxSmallSize-mallocHeaderSize {
		if reqSize <= smallSizeMax-8 {
			return uintptr(sizeClassToSize[sizeToSizeClass8[divRoundUp(reqSize, smallSizeDiv)]])
		}
		return uintptr(sizeClassToSize[sizeToSizeClass128[divRoundUp(reqSize-smallSizeMax, largeSizeDiv)]])
	}
	reqSize += pageSize - 1
	if reqSize < size {
		return size
	}
	return reqSize &^ (pageSize - 1)
}

