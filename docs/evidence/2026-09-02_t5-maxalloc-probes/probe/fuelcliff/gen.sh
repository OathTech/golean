#!/usr/bin/env bash
# Generator for the flat-struct fuel-cliff probe (maxAlloc audit fix round
# F1, 2026-09-02). Emits <outdir>/main.go: two structs of N single-byte
# fields (N = 1023 and 5000 — the first is the pre-fix cliff of the shared
# 1024 `typeResolutionFuel` when it was spent once per FIELD; the second is
# well past it) and, per struct, four import-free subjects the machine can
# run via `golean native-json-run --function <subject>` and gc via
# `tools/coverageharness --subject <subject>`:
#   cliff<N>MakeStore  make([]W,2) + a field store          (gc: 27)
#   cliff<N>MakeZero   make([]W,0)                          (gc: 0)
#   cliff<N>MakeNeg    n:=-1; make([]W,n)                   (gc: panic makeslice: len out of range)
#   cliff<N>Append     append(nil []W, W{})                 (gc: 1)
# The generated file is NOT tracked (it is ~150 KB of field names); this
# script is its producer of record. Usage: gen.sh <outdir>
set -euo pipefail
out="${1:?usage: gen.sh <outdir>}"
mkdir -p "$out"
{
  echo "// GENERATED by docs/evidence/2026-09-02_t5-maxalloc-probes/probe/fuelcliff/gen.sh — do not edit."
  echo "package main"
  echo
  for n in 1023 5000; do
    echo "type W$n struct {"
    for ((i = 0; i < n; i++)); do echo "	f$i byte"; done
    echo "}"
    echo
    echo "func cliff${n}MakeStore() int {"
    echo "	s := make([]W$n, 2)"
    echo "	s[1].f0 = 7"
    echo "	return len(s)*10 + int(s[1].f0)"
    echo "}"
    echo
    echo "func cliff${n}MakeZero() int {"
    echo "	s := make([]W$n, 0)"
    echo "	return len(s)"
    echo "}"
    echo
    echo "func cliff${n}MakeNeg() int {"
    echo "	n := -1"
    echo "	s := make([]W$n, n)"
    echo "	return len(s)"
    echo "}"
    echo
    echo "func cliff${n}Append() int {"
    echo "	var s []W$n"
    echo "	s = append(s, W$n{})"
    echo "	return len(s)"
    echo "}"
    echo
  done
  echo "func main() {}"
} > "$out/main.go"
echo "wrote $out/main.go"
